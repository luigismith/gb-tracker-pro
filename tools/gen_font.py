def emit_tile(rows):
    # 2bpp planar: each row -> 2 bytes (plane0, plane1)
    # We use plane0 = bitmap, plane1 = 0
    out = []
    for r in rows:
        out.append(r & 0xFF)
        out.append(0)
    return out


def main():
    out_path = Path(sys.argv[1] if len(sys.argv) > 1 else 'src/font.asm')

    # Build a 128-tile font (0x00..0x7F), each 16 bytes
    tiles = [[0] * 16 for _ in range(128)]
    for ch, bits in FONT.items():
        idx = ord(ch) - 0x20  # slot 0 = space (which maps to tile 0)
        if 0 <= idx < 128:
            tiles[idx] = emit_tile(bits)
    for slot, bits in EXTRA.items():
        if 0 <= slot < 128:
            tiles[slot] = emit_tile(bits)

    lines = []
    lines.append('; Auto-generated by tools/gen_font.py — do not edit by hand.')
    lines.append('SECTION "Font", ROM0')
    lines.append('FontTiles::')
    for i, tile in enumerate(tiles):
        ch = chr(i + 0x20) if 0x20 + i < 0x7F else '?'
        ch_disp = ch if 0x20 <= i + 0x20 < 0x7F and ch.isprintable() else '?'
        hexvals = ', '.join(f'${b:02X}' for b in tile)
        lines.append(f'    DB {hexvals}  ; tile ${i:02X} = {ch_disp!r}')
    lines.append('FontTiles_End::')
    out_path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print(f'Wrote {out_path} ({len(tiles)} tiles, {len(tiles)*16} bytes)')


if __name__ == '__main__':
    main()
